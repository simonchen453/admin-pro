package com.adminpro.system.rbac.domains.entity.userrole;

import com.adminpro.framework.base.entity.BaseAuditEntity;
import com.adminpro.framework.base.validator.IValidatorGroup;
import com.adminpro.framework.jdbc.annotation.AutoGeneratedKey;
import com.adminpro.framework.jdbc.annotation.Column;
import com.adminpro.framework.jdbc.annotation.PrimaryKey;
import com.adminpro.framework.jdbc.annotation.Table;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import lombok.Data;
import lombok.EqualsAndHashCode;

/**
 * 用户角色分配表 sys_user_role_assign_tbl
 *
 * @author simon
 * @date 2018-09-06
 */
@Data
@EqualsAndHashCode(callSuper = false)
@Table(name = UserRoleAssignEntity.TABLE_NAME)
public class UserRoleAssignEntity extends BaseAuditEntity {
    private static final long serialVersionUID = 1L;
    /**
     * 表名
     */
    public static final String TABLE_NAME = "SYS_USER_ROLE_ASSIGN_TBL";

    /**
     * ID
     */
    public static final String COL_ID = "COL_ID";
    /**
     * 用户ID
     */
    public static final String COL_USER_ID = "COL_USER_ID";
    /**
     * 角色ID
     */
    public static final String COL_ROLE_ID = "COL_ROLE_ID";
    /**
     * 备注
     */
    public static final String COL_REMARKS = "COL_REMARKS";

    /**
     * ID
     */
    @NotBlank(groups = IValidatorGroup.Update.class)
    @Size(max = 64)
    @AutoGeneratedKey
    @PrimaryKey
    @Column(name = COL_ID, type = Column.Type.STRING)
    private String id;
    /**
     * 用户ID
     */
    @NotBlank
    @Size(max = 64)
    @Column(name = COL_USER_ID, type = Column.Type.STRING)
    private String userId;
    /**
     * 角色ID
     */
    @NotBlank
    @Size(max = 64)
    @Column(name = COL_ROLE_ID, type = Column.Type.STRING)
    private String roleId;
    /**
     * 备注
     */
    @Size(max = 255)
    @Column(name = COL_REMARKS, type = Column.Type.STRING)
    private String remarks;

}
